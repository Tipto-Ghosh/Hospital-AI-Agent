# Wire back-reference onto Patient
def _patch_back_references() -> None:
    """Add long_term_context back-reference to Patient (one-to-one)."""
    try:
        from app.db.models.patient import Patient

        if not hasattr(Patient, "long_term_context"):
            Patient.long_term_context = relationship(
                "PatientLongTermContext",
                back_populates="patient",
                lazy="select",
                uselist=False,
                cascade="all, delete-orphan",
            )
        logging.debug("Long term context back-reference patched onto Patient successfully.")
    except Exception as exc:
        logging.exception("Failed to patch long term context back-reference onto Patient.")
        raise CustomException(
            error_message="Failed to wire long term context back-reference for Patient.",
            error_detail=str(exc),
        ) from exc


_patch_back_references()